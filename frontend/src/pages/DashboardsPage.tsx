import React, { useState, useEffect } from "react";
import { Navbar, Sidebar } from "../components/layout/Navigation";
import { Dashboard } from "../types";
import { dashboardApi } from "../api/client";
import { ChartRenderer } from "../components/analysis/ChartRenderer";
import { 
  Layers, 
  Trash2, 
  Plus, 
  Eye, 
  Calendar, 
  FileText,
  X
} from "lucide-react";

export const DashboardsPage: React.FC = () => {
  const [dashboards, setDashboards] = useState<Dashboard[]>([]);
  const [loading, setLoading] = useState(true);
  const [activeDashboard, setActiveDashboard] = useState<Dashboard | null>(null);

  useEffect(() => {
    fetchDashboards();
  }, []);

  const fetchDashboards = async () => {
    try {
      const res = await dashboardApi.list();
      setDashboards(res.data);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  const handleOpenDashboard = async (id: number) => {
    try {
      const res = await dashboardApi.get(id);
      setActiveDashboard(res.data);
    } catch {
      alert("Failed to load dashboard details");
    }
  };

  const handleDelete = async (id: number, e: React.MouseEvent) => {
    e.stopPropagation();
    if (!confirm("Are you sure you want to delete this dashboard?")) return;
    try {
      await dashboardApi.delete(id);
      if (activeDashboard?.id === id) setActiveDashboard(null);
      fetchDashboards();
    } catch {
      alert("Failed to delete dashboard");
    }
  };

  return (
    <div className="min-h-screen bg-gray-50 flex flex-col">
      <Navbar />

      <div className="flex flex-1">
        <Sidebar />

        <main className="flex-1 p-8 max-w-6xl mx-auto space-y-6">
          <div className="space-y-1">
            <h1 className="text-2xl font-extrabold text-gray-900 tracking-tight">Saved Dashboards</h1>
            <p className="text-xs text-gray-500">Curate, compare, and customize multiple dashboard alternatives generated by the Visualization Agent.</p>
          </div>

          {loading ? (
            <div className="p-12 text-center text-xs text-gray-400">Loading dashboards...</div>
          ) : dashboards.length === 0 ? (
            <div className="bg-white border border-gray-200 rounded-2xl p-12 text-center space-y-3">
              <Layers className="w-10 h-10 text-gray-300 mx-auto" />
              <p className="text-sm font-semibold text-gray-700">No saved dashboards yet</p>
              <p className="text-xs text-gray-400">Perform an analysis in the AI Studio and click "Add to Dashboard".</p>
            </div>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
              {dashboards.map((d) => (
                <div
                  key={d.id}
                  onClick={() => handleOpenDashboard(d.id)}
                  className="bg-white border border-gray-200 rounded-2xl p-5 shadow-2xs space-y-4 hover:shadow-sm cursor-pointer transition"
                >
                  <div className="flex items-start justify-between">
                    <div>
                      <h3 className="text-sm font-bold text-gray-900 truncate max-w-[200px]">{d.title}</h3>
                      <p className="text-[11px] text-gray-400">Dataset: {d.dataset_name}</p>
                    </div>

                    <button
                      onClick={(e) => handleDelete(d.id, e)}
                      className="p-1 text-gray-400 hover:text-red-600 transition"
                      title="Delete"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  </div>

                  <p className="text-xs text-gray-600 line-clamp-2">{d.description || "Interactive dashboard view."}</p>

                  <div className="pt-2 border-t border-gray-100 flex items-center justify-between text-xs text-brand-600 font-semibold">
                    <span className="flex items-center gap-1.5">
                      <Eye className="w-3.5 h-3.5" />
                      View Dashboard ({d.components?.length || 1} widgets)
                    </span>
                  </div>
                </div>
              ))}
            </div>
          )}

          {/* Active Dashboard Full View Modal / Canvas */}
          {activeDashboard && (
            <div className="fixed inset-0 bg-black/40 backdrop-blur-xs flex items-center justify-center z-50 p-4">
              <div className="bg-white rounded-2xl max-w-4xl w-full p-6 shadow-xl max-h-[90vh] overflow-y-auto space-y-6">
                <div className="flex items-center justify-between pb-3 border-b border-gray-100">
                  <div>
                    <h3 className="text-base font-bold text-gray-900">{activeDashboard.title}</h3>
                    <p className="text-xs text-gray-500">{activeDashboard.description}</p>
                  </div>
                  <button onClick={() => setActiveDashboard(null)} className="text-gray-400 hover:text-gray-600 font-bold">
                    <X className="w-5 h-5" />
                  </button>
                </div>

                {/* Dashboard Components */}
                <div className="space-y-6">
                  {activeDashboard.components?.map((comp, idx) => (
                    <div key={idx} className="bg-gray-50 border border-gray-200 rounded-2xl p-5 space-y-3">
                      <h4 className="text-xs font-bold text-gray-800 uppercase tracking-wider">{comp.title}</h4>
                      <ChartRenderer
                        chartType={comp.component_type}
                        data={comp.data_cache || []}
                        xAxis={comp.config?.x_axis}
                        yAxis={comp.config?.y_axis}
                      />
                    </div>
                  ))}
                </div>
              </div>
            </div>
          )}
        </main>
      </div>
    </div>
  );
};
